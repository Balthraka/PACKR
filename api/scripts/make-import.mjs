// Turns the Supabase exports into import/seed.sql (user IDs and row IDs are kept).
// Usage: node scripts/make-import.mjs <auth_users.csv> <packr_trips_rows.csv> [--email <userId>=<newEmail> ...] [--out <file>]
//   --email sets the email on that imported user (used to link by hand to the Google address they will sign in with).
//   auth_users.csv       columns: id,email,created_at
//   packr_trips_rows.csv columns: id,user_id,data,updated_at
// Safe to run again: existing IDs are updated in place, and sign-in links (the identities
// table, and the old google_sub / microsoft_sub columns on users) are kept. import/ is git-ignored: the output contains real emails and trip data.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { parseCsv } from './csv.mjs';

const ms = (ts) => {
  const t = Date.parse(ts.replace(' ', 'T').replace(/\+00$/, 'Z'));
  if (Number.isNaN(t)) throw new Error('bad timestamp: ' + ts);
  return t;
};
const sql = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const args = process.argv.slice(2);
const overrides = new Map();
let outPath = 'import/seed.sql';
const files = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--email') {
    const [id, email] = (args[++i] || '').split('=');
    if (!id || !email || !email.includes('@')) { console.error('bad --email, expected <userId>=<email>'); process.exit(1); }
    overrides.set(id, email.trim().toLowerCase());
  } else if (args[i] === '--out') {
    outPath = args[++i];
  } else files.push(args[i]);
}
const [usersPath, tripsPath] = files;
if (!usersPath || !tripsPath) { console.error('usage: make-import.mjs <users.csv> <trips.csv>'); process.exit(1); }

const users = parseCsv(readFileSync(usersPath, 'utf8'));
const trips = parseCsv(readFileSync(tripsPath, 'utf8'));
const ids = new Set(users.map((u) => u.id));
for (const id of overrides.keys()) if (!ids.has(id)) { console.error('--email: no such user ' + id); process.exit(1); }

const out = ['-- generated by scripts/make-import.mjs; do not commit'];
for (const u of users) {
  out.push(`INSERT INTO users (id, email, display_name, created_at) VALUES (${sql(u.id)}, ${sql(overrides.get(u.id) || u.email.trim().toLowerCase())}, NULL, ${ms(u.created_at)})
  ON CONFLICT(id) DO UPDATE SET email = excluded.email, created_at = excluded.created_at;`);
}
for (const t of trips) {
  if (!ids.has(t.user_id)) throw new Error(`trips row ${t.id} belongs to unknown user ${t.user_id}`);
  const d = JSON.parse(t.data); // fail now if the blob is not valid JSON
  if (!Array.isArray(d.trips)) throw new Error(`row ${t.id}: no trips array`);
  // Re-serialise in the same shape the API writes.
  const text = JSON.stringify({ trips: d.trips, templates: d.templates || [] });
  out.push(`INSERT INTO packr_trips (id, user_id, data, version, updated_at) VALUES (${sql(t.id)}, ${sql(t.user_id)}, ${sql(text)}, 1, ${ms(t.updated_at)})
  ON CONFLICT(id) DO UPDATE SET data = excluded.data, updated_at = excluded.updated_at, version = packr_trips.version + 1;`);
}
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out.join('\n') + '\n');
console.log(`users: ${users.length}, trip rows: ${trips.length} -> ${outPath}`);
